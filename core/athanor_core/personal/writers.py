"""Write genotypes in the vendors' raw-file layouts (for tests and validation:
genotypes with a known truth are written as each vendor would, then read
back through the parser)."""
from __future__ import annotations

import numpy as np

B = "ACGT"
ANC_CHROM = {23: "23", 24: "24", 25: "25", 26: "26"}
NAME = {23: "X", 24: "Y", 25: "XY", 26: "MT"}


def _gt(ref: int, alt: int, dosage: int) -> tuple[str, str] | None:
    if dosage < 0:
        return None
    r, a = B[ref], B[alt]
    return {0: (r, r), 1: (r, a), 2: (a, a)}[int(dosage)]


def write(path, fmt: str, rsid, chrom, pos, ref, alt, dosage, haploid: dict | None = None):
    """fmt: 23andme, ancestry, myheritage, ftdna, livingdna, vcf.
    haploid: extra {chrom: [(pos, base)]} for Y and MT calls."""
    lines = []
    if fmt == "23andme":
        lines += ["# This data file generated by 23andMe at: Thu Jan 01 00:00:00 2026", "#",
                  "# rsid\tchromosome\tposition\tgenotype"]
    elif fmt == "ancestry":
        lines += ["#AncestryDNA raw data download", "#Genotypes are reported on the forward (+) strand of GRCh37",
                  "rsid\tchromosome\tposition\tallele1\tallele2"]
    elif fmt == "myheritage":
        lines += ["# MyHeritage DNA raw data.", "# Reference: build 37", "RSID,CHROMOSOME,POSITION,RESULT"]
    elif fmt == "ftdna":
        lines += ["RSID,CHROMOSOME,POSITION,RESULT"]
    elif fmt == "livingdna":
        lines += ["# Living DNA customer genotype data download file version: 1.0.1", "# rsid\tchromosome\tposition\tgenotype"]
    elif fmt == "vcf":
        lines += ["##fileformat=VCFv4.2", "##reference=GRCh37", '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">',
                  "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE"]
    for rs, c, p, r, a, d in zip(rsid, chrom, pos, ref, alt, dosage):
        g = _gt(int(r), int(a), int(d))
        rid = f"rs{rs}" if rs > 0 else f"i{p}"
        if fmt in ("23andme", "livingdna"):
            lines.append(f"{rid}\t{c}\t{p}\t{''.join(g) if g else '--'}")
        elif fmt == "ancestry":
            lines.append(f"{rid}\t{c}\t{p}\t{g[0] if g else 0}\t{g[1] if g else 0}")
        elif fmt in ("myheritage", "ftdna"):
            lines.append(f'"{rid}","{c}","{p}","{"".join(g) if g else "--"}"')
        elif fmt == "vcf":
            if g is None:
                gt = "./."
            else:
                gt = {0: "0/0", 1: "0/1", 2: "1/1"}[int(d)]
            lines.append(f"{c}\t{p}\t{rid}\t{B[int(r)]}\t{B[int(a)]}\t.\tPASS\t.\tGT\t{gt}")
    for c, calls in (haploid or {}).items():
        for p, b in calls:
            if fmt in ("23andme", "livingdna"):
                lines.append(f"i{c}_{p}\t{NAME[c]}\t{p}\t{b}")
            elif fmt == "ancestry":
                lines.append(f"i{c}_{p}\t{ANC_CHROM[c]}\t{p}\t{b}\t{b}")
            elif fmt in ("myheritage", "ftdna"):
                lines.append(f'"i{c}_{p}","{NAME[c]}","{p}","{b}{b}"')
            elif fmt == "vcf":
                lines.append(f"{NAME[c]}\t{p}\ti{c}_{p}\t{b}\t.\t.\tPASS\t.\tGT\t0")
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
